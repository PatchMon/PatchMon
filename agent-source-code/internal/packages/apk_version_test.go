func TestAPKVersionComparer(t *testing.T) {
	if apkVersionComparer(2)("0.012", "0.04") != 1 {
		t.Error("apk 2 should use the legacy ordering")
	}
	for _, major := range []int{0, 3} {
		if apkVersionComparer(major)("0.012", "0.04") != -1 {
			t.Errorf("apk major %d should use the v3 ordering", major)
		}
	}
}

func TestAPKVersionValid(t *testing.T) {
	valid := []string{"1.0", "1.0-r0", "1.37.0-r30", "1.1.1k-r0", "1.0_rc1_p2", "3.25.0_alpha20260805-r0", "1.0~abcdef-r1", "0"}
	invalid := []string{"", "abc", "1..2", "1.0_foo", "1.0-x", "1.0--r1", "1.2a.3", "1.0-r1~x"}
	for _, v := range valid {
		if !apkVersionValid(v) {
			t.Errorf("%q should be valid", v)
		}
	}
	for _, v := range invalid {
		if apkVersionValid(v) {
			t.Errorf("%q should be invalid", v)
		}
	}
}
