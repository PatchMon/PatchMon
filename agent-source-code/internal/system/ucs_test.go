package system

import (
	"os"
	"path/filepath"
	"testing"
)

func TestUCSRelease(t *testing.T) {
	cases := []struct {
		name    string
		content string
		want    string
	}{
		{"ucs 5.2", "# generated by univention-config-registry\n\nDISTRIB_ID=Univention\nDISTRIB_RELEASE=\"5.2-7 errata606\"\nDISTRIB_DESCRIPTION=\"Univention Corporate Server 5.2-7 errata606\"\n", "5.2-7 errata606"},
		{"ucs 5.0", "DISTRIB_ID=Univention\nDISTRIB_RELEASE=\"5.0-10 errata1220\"\n", "5.0-10 errata1220"},
		{"ubuntu", "DISTRIB_ID=Ubuntu\nDISTRIB_RELEASE=24.04\n", ""},
		{"univention without a release", "DISTRIB_ID=Univention\n", ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "lsb-release")
			if err := os.WriteFile(path, []byte(tc.content), 0o600); err != nil {
				t.Fatal(err)
			}
			if got := ucsRelease(path); got != tc.want {
				t.Fatalf("ucsRelease() = %q, want %q", got, tc.want)
			}
		})
	}
	if got := ucsRelease(filepath.Join(t.TempDir(), "missing")); got != "" {
		t.Fatalf("missing lsb-release: got %q", got)
	}
}
